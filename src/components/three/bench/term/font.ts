const glyph = (ch: string) => (GLYPHS[ch.toUpperCase()] ?? GLYPHS['?']).split('|');

/** The width in text cells of a word in the dot font. */
export const bigWidth = (s: string) => [...s].reduce((w, ch) => w + glyph(ch)[0].length + 1, 0) - 1;

/** A line of text in the dot font: four rows of half blocks. */
export function big(s: string): string[] {
  const rows: string[] = Array(7).fill('');
  [...s].forEach((ch, i) => {
    const g = glyph(ch);
    for (let y = 0; y < 7; y++) rows[y] += (i ? '.' : '') + g[y];
  });
  rows.push('.'.repeat(rows[0].length));
  const out: string[] = [];
  for (let y = 0; y < 8; y += 2) {
    let line = '';
    for (let x = 0; x < rows[y].length; x++) {
      const a = rows[y][x] === '#';
      const b = rows[y + 1][x] === '#';
      line += a && b ? '█' : a ? '▀' : b ? '▄' : ' ';
    }
    out.push(line.replace(/\s+$/, ''));
  }
  return out;
}

/** Text in the dot font, broken onto as many banners as it takes to fit `cols`. */
export function banner(text: string, cols: number): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (cur && bigWidth(next) > cols) {
      lines.push(cur);
      cur = w;
    } else cur = next;
  }
  if (cur) lines.push(cur);
  const out: string[] = [];
  lines.forEach((l, i) => {
    // a word longer than the screen is cut to what fits
    let fit = l;
    while (fit.length > 1 && bigWidth(fit) > cols) fit = fit.slice(0, -1);
    if (i) out.push('');
    out.push(...big(fit));
  });
  return out;
}
